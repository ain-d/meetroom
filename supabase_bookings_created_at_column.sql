-- ทำไมต้องรันไฟล์นี้:
-- หน้าอนุมัติการจอง (BookingAdmin.jsx) ต้องใช้คอลัมน์ "created_at" (เวลาที่กดจอง)
-- เพื่อเรียงรายการที่ "รออนุมัติ" ให้จองล่าสุดขึ้นก่อน ถ้าตาราง bookings ของคุณ
-- มีคอลัมน์นี้อยู่แล้ว (ตารางที่สร้างผ่าน Supabase Table Editor ส่วนใหญ่มีให้อัตโนมัติ)
-- คำสั่งนี้จะไม่ทำอะไร ปลอดภัยที่จะรันซ้ำได้เสมอ
--
-- วิธีติดตั้ง: Supabase Dashboard -> SQL Editor -> วางไฟล์นี้ -> Run
-- ============================================================================

ALTER TABLE public.bookings
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

-- หมายเหตุ: ถ้าคอลัมน์นี้เพิ่งถูกสร้างใหม่ (ตารางไม่เคยมีมาก่อน) แถวการจองเก่าๆ
-- ที่มีอยู่แล้วจะได้ค่า created_at เป็น "เวลาที่รันคำสั่งนี้" ทั้งหมด (ไม่ใช่เวลาที่จองจริง)
-- เพราะข้อมูลเวลาที่จองจริงของรายการเก่าไม่ได้ถูกเก็บไว้ที่ไหน ผลคือการเรียงลำดับ
-- "จองล่าสุดก่อน" จะแม่นยำสำหรับการจองใหม่ๆ ตั้งแต่วันนี้เป็นต้นไป
